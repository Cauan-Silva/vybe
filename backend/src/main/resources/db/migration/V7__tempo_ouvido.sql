-- "Seu mês no VYBE": quanto tempo cada música foi ouvida e quais vídeos foram assistidos.

-- Segundos realmente ouvidos em cada reprodução (o player manda enquanto toca).
-- Nas reproduções antigas fica nulo, e o resumo usa a duração da música.
ALTER TABLE reproducao ADD COLUMN segundos_ouvidos INTEGER;

-- Cada vez que um vídeo é aberto, com o tempo assistido. Guarda uma cópia dos dados do vídeo
-- para montar o resumo sem gastar a cota da API do YouTube.
CREATE TABLE visualizacao_video (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    video_id            VARCHAR(20)  NOT NULL,
    titulo              VARCHAR(300) NOT NULL,
    canal               VARCHAR(150),
    canal_id            VARCHAR(40),
    capa_url            VARCHAR(500),
    assistido_em        TIMESTAMP    NOT NULL,
    segundos_assistidos INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX idx_visualizacao_video_usuario ON visualizacao_video (usuario_id, assistido_em);
