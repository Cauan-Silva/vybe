-- Conta do Spotify ligada a um usuário do VYBE (no máximo uma por usuário).
-- Os tokens permitem ler playlists e mais ouvidos em nome da pessoa.
CREATE TABLE spotify_conta (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL UNIQUE REFERENCES usuario (id) ON DELETE CASCADE,
    spotify_id    VARCHAR(100) NOT NULL,
    nome          VARCHAR(150),
    access_token  TEXT         NOT NULL,
    refresh_token TEXT         NOT NULL,
    expira_em     TIMESTAMP    NOT NULL,
    conectado_em  TIMESTAMP    NOT NULL
);
