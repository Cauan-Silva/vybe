CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    email      VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    criado_em  TIMESTAMP    NOT NULL
);

CREATE TABLE artista (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(150) NOT NULL,
    criado_em TIMESTAMP    NOT NULL
);
-- "Ana" e "ana" são o mesmo artista
CREATE UNIQUE INDEX uq_artista_nome ON artista (LOWER(nome));

CREATE TABLE album (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo       VARCHAR(200) NOT NULL,
    artista_id   BIGINT       NOT NULL REFERENCES artista (id),
    capa_arquivo VARCHAR(100),
    criado_em    TIMESTAMP    NOT NULL
);
CREATE UNIQUE INDEX uq_album_artista_titulo ON album (artista_id, LOWER(titulo));

-- origem = UPLOAD (arquivo guardado pela API) ou JAMENDO (fase 2, url_externa)
CREATE TABLE musica (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo           VARCHAR(200) NOT NULL,
    artista_id       BIGINT       NOT NULL REFERENCES artista (id),
    album_id         BIGINT       NOT NULL REFERENCES album (id),
    duracao_segundos INTEGER      NOT NULL CHECK (duracao_segundos > 0),
    origem           VARCHAR(20)  NOT NULL,
    arquivo          VARCHAR(100),
    content_type     VARCHAR(100),
    tamanho_bytes    BIGINT,
    url_externa      VARCHAR(500),
    id_externo       VARCHAR(50),
    enviada_por      BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    criada_em        TIMESTAMP    NOT NULL
);
CREATE INDEX idx_musica_album ON musica (album_id);
CREATE INDEX idx_musica_artista ON musica (artista_id);
CREATE INDEX idx_musica_criada_em ON musica (criada_em DESC);

CREATE TABLE curtida (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT    NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    musica_id  BIGINT    NOT NULL REFERENCES musica (id) ON DELETE CASCADE,
    criada_em  TIMESTAMP NOT NULL,
    UNIQUE (usuario_id, musica_id)
);

CREATE TABLE reproducao (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT    NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    musica_id  BIGINT    NOT NULL REFERENCES musica (id) ON DELETE CASCADE,
    tocada_em  TIMESTAMP NOT NULL
);
CREATE INDEX idx_reproducao_usuario ON reproducao (usuario_id, tocada_em DESC);

CREATE TABLE playlist (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    dono_id       BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    criada_em     TIMESTAMP    NOT NULL,
    atualizada_em TIMESTAMP    NOT NULL
);

CREATE TABLE playlist_musica (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id   BIGINT    NOT NULL REFERENCES playlist (id) ON DELETE CASCADE,
    musica_id     BIGINT    NOT NULL REFERENCES musica (id) ON DELETE CASCADE,
    posicao       INTEGER   NOT NULL,
    adicionada_em TIMESTAMP NOT NULL,
    UNIQUE (playlist_id, musica_id)
);
