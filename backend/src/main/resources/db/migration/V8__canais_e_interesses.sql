-- Aba Vídeos personalizada: canais que a pessoa segue e temas de interesse.
-- Guardamos nome e foto do canal para listar sem gastar a cota da API do YouTube.
CREATE TABLE canal_seguido (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    canal_id   VARCHAR(40)  NOT NULL,
    nome       VARCHAR(150) NOT NULL,
    avatar_url VARCHAR(500),
    seguido_em TIMESTAMP    NOT NULL,
    UNIQUE (usuario_id, canal_id)
);
CREATE INDEX idx_canal_seguido_usuario ON canal_seguido (usuario_id, seguido_em DESC);

CREATE TABLE interesse_video (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT      NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    termo      VARCHAR(60) NOT NULL,
    criado_em  TIMESTAMP   NOT NULL
);
CREATE INDEX idx_interesse_video_usuario ON interesse_video (usuario_id, criado_em);
