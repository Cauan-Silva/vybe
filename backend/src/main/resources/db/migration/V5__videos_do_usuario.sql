-- Aba Vídeos: "Assistir depois", histórico e de onde parar cada vídeo, por usuário.
-- Guardamos uma cópia dos dados do vídeo (título, canal, miniatura) para montar as listas
-- sem gastar a cota da API do YouTube.
CREATE TABLE video_usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    video_id         VARCHAR(20)  NOT NULL,
    titulo           VARCHAR(300) NOT NULL,
    canal            VARCHAR(150),
    canal_id         VARCHAR(40),
    capa_url         VARCHAR(500),
    duracao_segundos INTEGER      NOT NULL DEFAULT 0,
    assistir_depois  BOOLEAN      NOT NULL DEFAULT FALSE,
    salvo_em         TIMESTAMP,
    assistido_em     TIMESTAMP,
    posicao_segundos INTEGER      NOT NULL DEFAULT 0,
    UNIQUE (usuario_id, video_id)
);
CREATE INDEX idx_video_usuario_historico ON video_usuario (usuario_id, assistido_em DESC);
CREATE INDEX idx_video_usuario_depois ON video_usuario (usuario_id, salvo_em DESC);
